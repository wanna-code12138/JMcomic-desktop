const assert = require('node:assert/strict')

module.exports = async ({ win, js, wait, clickSelector, clickText, screenshot, mark }) => {
  const wc = win.webContents
  const key = async (keyCode, modifiers = []) => {
    wc.sendInputEvent({ type: 'keyDown', keyCode, modifiers }); wc.sendInputEvent({ type: 'keyUp', keyCode, modifiers })
  }
  assert.ok(await js(`Boolean(document.querySelector('[data-new-reader-tab]'))`), 'reader exposes the browser-style plus button')
  assert.ok(await js(`(()=>{const e=document.querySelector('.reader-tabs');return e.scrollHeight<=e.clientHeight+1||getComputedStyle(e).overflowY==='hidden'})()`), 'the tab strip never shows a vertical scrollbar')
  await clickSelector('[data-new-reader-tab]')
  await wait(`Boolean(document.querySelector('[data-reader-start]'))`, 'new tab start page')
  assert.equal(await js(`document.querySelectorAll('.reader-root').length`), 0, 'start page unloads background image sessions')
  await wait(`document.activeElement?.getAttribute('aria-label')==='搜索漫画或输入 JM 号'`, 'new tab search focus')
  await wc.insertText('101')
  await key('Return')
  await wait(`document.querySelector('[data-browse-pane]').textContent.includes('山间来信')`, 'number opens the central detail')
  await clickText('开始阅读')
  await wait(`document.querySelector('[data-reader-tab="online:101"]')?.getAttribute('aria-selected')==='true'`, 'existing book deduplicated')
  assert.equal(await js(`document.querySelectorAll('[data-reader-tab]').length`), 2)
  await js(`document.querySelector('[data-reader-tab="online:101"]').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,clientX:900,clientY:70}))`)
  await clickText('重命名标签')
  await wait(`Boolean(document.querySelector('[aria-label="标签名称"]'))`, 'rename dialog')
  await js(`document.querySelector('[aria-label="标签名称"]').select()`)
  await wc.insertText('我的书签')
  await clickText('保存名称')
  await wait(`document.querySelector('[data-reader-tab="online:101"]').textContent.includes('我的书签')`, 'custom title')
  await js(`document.querySelector('[data-reader-tab="online:101"]').focus()`)
  await key('F10', ['shift'])
  await clickText('固定标签')
  await wait(`document.querySelector('.reader-tab')?.dataset.pinned==='true'`, 'pin partition')
  await key('T', ['control'])
  await wait(`document.querySelectorAll('[data-reader-tab]').length===3`, 'Ctrl T')
  await js(`document.querySelector('[data-reader-start] h1').focus()`)
  await key('W', ['control'])
  await wait(`document.querySelectorAll('[data-reader-tab]').length===2`, 'Ctrl W')
  await key('T', ['control','shift'])
  await wait(`document.querySelectorAll('[data-reader-tab]').length===3`, 'Ctrl Shift T')
  const ids = await js(`[...document.querySelectorAll('[data-reader-tab]')].map(e=>e.dataset.readerTab)`)
  await clickSelector(`[data-reader-tab="${ids[2]}"]`)
  await wait(`document.querySelector('[data-reader-tab="${ids[2]}"]')?.getAttribute('aria-selected')==='true' && document.activeElement?.tagName==='INPUT'`, 'activate tab before reordering')
  await js(`document.querySelector('[data-reader-tab="${ids[2]}"]').focus()`)
  await key('PageUp', ['control','shift'])
  await wait(`document.querySelectorAll('[data-reader-tab]')[1]?.dataset.readerTab==='${ids[2]}'`, 'keyboard reorder')
  await js(`(()=>{const els=[...document.querySelectorAll('[data-reader-tab]')],dt=new DataTransfer();els[1].dispatchEvent(new DragEvent('dragstart',{bubbles:true,dataTransfer:dt}));const r=els[2].getBoundingClientRect();els[2].dispatchEvent(new DragEvent('dragover',{bubbles:true,cancelable:true,clientX:r.right-1,dataTransfer:dt}));els[2].dispatchEvent(new DragEvent('drop',{bubbles:true,cancelable:true,clientX:r.right-1,dataTransfer:dt}));els[1].dispatchEvent(new DragEvent('dragend',{bubbles:true,dataTransfer:dt}))})()`)
  await wait(`document.querySelectorAll('[data-reader-tab]')[2]?.dataset.readerTab==='${ids[2]}'`, 'pointer reorder commits on drop')
  await clickSelector('[data-reader-tab-list]')
  await wait(`Boolean(document.querySelector('[aria-label="筛选打开的标签"]'))`, 'tab overflow switcher')
  await key('Escape')
  await screenshot('tabs-new-start')
  mark('plus, start search, rename, pin, close/reopen shortcuts, keyboard and pointer reorder, overflow')
}
