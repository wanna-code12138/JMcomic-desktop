const assert = require('node:assert/strict')

module.exports = async ({ win, js, wait, clickText, clickSelector, showTools, screenshot, mark, rejectSaves }) => {
  const wc = win.webContents
  const press = async keyCode => {
    wc.sendInputEvent({ type: 'keyDown', keyCode }); wc.sendInputEvent({ type: 'keyUp', keyCode })
    await new Promise(resolve => setTimeout(resolve, 70))
  }
  const tab = id => `[data-reader-tab="${id}"]`
  const select = async id => { await js(`document.querySelector('${tab(id)}').click()`); await wait(`document.querySelector('${tab(id)}')?.getAttribute('aria-selected')==='true' && !document.querySelector('[data-reader-pending]')`, `activate ${id}`) }
  const page = () => js(`document.querySelector('[data-reader-progress]')?.dataset.currentPage`)
  const anchor = async () => {
    await wait(`Boolean(document.querySelector('[data-reader-viewport] [data-index="'+(Number(document.querySelector('[data-reader-progress]')?.dataset.currentPage)-1)+'"]'))`, 'current page mounted after layout restoration')
    return js(`(()=>{const v=document.querySelector('[data-reader-viewport]'),page=Number(document.querySelector('[data-reader-progress]').dataset.currentPage),r=v.querySelector('[data-index="'+(page-1)+'"]').getBoundingClientRect();return {page,offset:(v.getBoundingClientRect().top+Number(v.dataset.readingInset)-r.top)/r.height}})()`)
  }
  const jump = async value => {
    await clickText('阅读进度')
    await wait(`document.querySelector('[aria-label="跳转页码"]').getBoundingClientRect().height>0`, 'visible page input')
    await js(`(()=>{const e=document.querySelector('[aria-label="跳转页码"]');e.focus();e.select()})()`)
    await wc.insertText(String(value))
    await clickText('跳转')
    await wait(`document.querySelector('[data-reader-progress]')?.dataset.currentPage==='${value}' && !document.querySelector('.reader-page-navigation[open]')`, 'page jump')
    await wait(`Boolean(document.querySelector('[data-index="${value-1}"] [data-reader-image-status="ready"]'))`, 'jumped page decoded')
    await wait(`document.activeElement===document.querySelector('[data-reader-viewport]')`, 'focus returned after a page jump')
  }
  const geometry = () => js(`(()=>{const rect=s=>{const e=document.querySelector(s),r=e?.getBoundingClientRect();return r?{x:r.x,width:r.width,right:r.right}:null};return {nav:rect('nav'),browse:rect('[data-browse-pane]'),reader:rect('[data-reader-workspace]')}})()`)
  let bounds = await geometry()
  assert.ok(bounds.nav && bounds.nav.width <= 65, 'entering reading must preserve a compact icon navigation rail')
  assert.ok(bounds.browse.width >= 300 && bounds.reader.width >= 480)
  assert.ok(bounds.nav.right <= bounds.browse.x + 1 && bounds.browse.right <= bounds.reader.x + 1)
  assert.equal(await js(`document.querySelectorAll('[data-reader-tab]').length`), 1)
  const toolsVisible = () => js(`Boolean(document.querySelector('.reader-toolbar')?.getBoundingClientRect().height)`)
  assert.equal(await toolsVisible(), false, 'reader tools must start collapsed')
  await js(`document.querySelector('[data-reader-viewport]').dispatchEvent(new PointerEvent('pointermove',{bubbles:true,clientX:300,clientY:200}))`)
  assert.equal(await toolsVisible(), false, 'moving over the comic must not reveal controls')
  assert.equal(await js(`Boolean(document.querySelector('.reader-footer,.reader-quiet-progress'))`), false, 'no bottom floating controls may cover the comic')
  await screenshot('workspace-three-pane')
  await js(`document.querySelector('nav [aria-label="展开导航"]').click()`)
  await wait(`document.querySelector('nav').getBoundingClientRect().width>=208`, 'manual navigation expansion')
  assert.ok((await geometry()).reader.width >= 480)
  await js(`document.querySelector('nav [aria-label="收起导航"]').click()`)
  await jump(8)
  assert.ok(await js(`document.activeElement===document.querySelector('[data-reader-viewport]')`), 'jumping from the header returns focus to reading')
  await press('Right')
  await wait(`document.querySelector('[data-reader-progress]')?.dataset.currentPage==='9'`, 'keyboard continues immediately after a page jump')
  await jump(8)
  const before = { height: await js(`document.querySelector('[data-reader-viewport]').clientHeight`), anchor: await anchor() }
  await showTools()
  assert.ok(await js(`document.querySelector('.reader-toolbar').getBoundingClientRect().bottom <= document.querySelector('[data-reader-viewport]').getBoundingClientRect().top + 1`), 'tools dock above rather than cover the comic')
  await wait(`document.querySelector('[data-reader-viewport]').clientHeight<=${before.height-38}`, 'docked toolbar takes one row')
  await screenshot('workspace-tools-open')
  await clickSelector('[data-reader-tools-toggle]')
  await wait(`document.querySelector('[data-reader-viewport]').clientHeight===${before.height}`, 'folding tools returns their height')
  assert.equal(await page(), '8')
  const after = await anchor()
  assert.ok(Math.abs(after.offset-before.anchor.offset)<0.01, `manual tools preserve the page-relative reading anchor: ${JSON.stringify({before:before.anchor,after})}`)
  await jump(8)
  await press('H')
  assert.equal(await toolsVisible(), true, 'H opens tools when the reading viewport owns focus')
  await press('H')
  assert.equal(await toolsVisible(), false, 'H closes tools without leaving the reading viewport')
  const afterShortcut = await anchor()
  assert.equal(await page(), '8', `tool shortcuts preserve the current page: ${JSON.stringify(afterShortcut)}`)
  await js(`window.__qaFirstReader=document.querySelector('.reader-root');window.__qaOldImages=[...window.__qaFirstReader.querySelectorAll('img')];window.__qaOldCanvases=[...window.__qaFirstReader.querySelectorAll('canvas')]`)
  await js(`document.querySelector('nav [aria-label="收藏"]').click()`)
  assert.ok(await js(`window.__qaFirstReader===document.querySelector('.reader-root')`), 'central navigation does not remount the reader')
  await js(`document.querySelector('nav [aria-label="收藏"]').focus()`); await press('End')
  assert.equal(await page(), '8', `navigation keyboard input must not turn reader pages: ${JSON.stringify({afterShortcut,current:await anchor()})}`)
  await wait(`Boolean([...document.querySelectorAll('.manga-card')].find(e=>e.textContent.includes('海边日记')&&e.getBoundingClientRect().width>0))`, 'second favorite')
  await js(`[...document.querySelectorAll('.manga-card')].find(e=>e.textContent.includes('海边日记')&&e.getBoundingClientRect().width>0).click()`)
  await clickText('开始阅读')
  await wait(`document.querySelectorAll('[data-reader-tab]').length===2 && document.querySelector('[data-reader-tab][aria-selected="true"]')?.textContent.includes('海边日记')`, 'second book tab')
  await wait(`Boolean(document.querySelector('[data-reader-image-status="ready"]'))`, 'second book image')
  assert.equal(await js(`window.__qaFirstReader.isConnected`), false, 'background reader must unmount')
  assert.ok(await js(`window.__qaOldImages.every(image=>!image.getAttribute('src'))`), 'background images must release their request subscriptions')
  assert.ok(await js(`window.__qaOldCanvases.every(canvas=>canvas.width===0 && canvas.height===0)`), 'background canvases must release their backing buffers')
  assert.equal(await js(`document.querySelectorAll('.reader-root').length`), 1)
  await jump(11)
  const beforeHide = await anchor()
  assert.equal(await toolsVisible(), false, 'opening another book preserves the collapsed tool choice')
  await js(`window.__qaRetainedReader=document.querySelector('.reader-root')`)
  await clickText('收起阅读侧栏')
  await wait(`document.querySelector('[data-reader-workspace]').getBoundingClientRect().width===0`, 'side pane hidden')
  assert.equal(await js(`document.querySelectorAll('[data-reader-tab]').length`), 2)
  assert.ok(await js(`window.__qaRetainedReader===document.querySelector('.reader-root')`), 'hiding retains the active reading session')
  await wait(`document.activeElement?.hasAttribute('data-reader-visibility-toggle')`, 'hidden pane moves focus to its restore button')
  await press('Tab')
  assert.ok(await js(`!document.activeElement?.closest('[data-reader-workspace]')`), 'hidden reading controls leave the tab order')
  await screenshot('workspace-hidden')
  win.setSize(960, 640)
  await clickText('显示阅读侧栏')
  await wait(`document.querySelector('[data-reader-workspace]').getBoundingClientRect().width>=480 && document.querySelector('[data-reader-progress]')?.dataset.currentPage==='11'`, 'side pane and anchor restored')
  assert.ok(await js(`window.__qaRetainedReader===document.querySelector('.reader-root')`))
  assert.ok(Math.abs((await anchor()).offset-beforeHide.offset)<0.01, 'resizing a hidden side pane preserves its page-relative reading anchor')
  win.setSize(1280, 860)
  await clickText('收起阅读侧栏')
  await clickText('开始阅读')
  await wait(`document.querySelector('[data-reader-workspace]').getBoundingClientRect().width>=480`, 'detail reopens hidden reader')
  assert.equal(await js(`document.querySelectorAll('[data-reader-tab]').length`), 2)
  assert.equal(await page(), '11')
  mark('manual docked tools reclaim space; sidebar visibility preserves tabs, session, focus and reading position')
  await select('online:101'); await wait(`document.querySelector('[data-reader-progress]')?.dataset.currentPage==='8'`, 'first book anchor')
  await select('online:102'); await wait(`document.querySelector('[data-reader-progress]')?.dataset.currentPage==='11'`, 'second book anchor')
  await js(`document.querySelector('${tab('online:102')}').focus()`)
  await press('Left')
  await wait(`document.querySelector('[data-reader-progress]')?.dataset.currentPage==='8' && document.activeElement?.dataset.readerTab==='online:101'`, 'keyboard tab and anchor')
  await press('Right')
  await wait(`document.querySelector('[data-reader-progress]')?.dataset.currentPage==='11' && document.activeElement?.dataset.readerTab==='online:102'`, 'keyboard return tab')
  await clickText('开始阅读')
  assert.equal(await js(`document.querySelectorAll('[data-reader-tab]').length`), 2, 'reopening a chapter must deduplicate')
  assert.equal(await page(), '11')
  mark('three panes, source-aware tabs, independent anchors, deduplication and background unmount')
  await wait(`Boolean(document.querySelector('[data-index="10"] [data-reader-image-status="ready"]'))`, 'active page decoded before visual evidence')
  await screenshot('workspace-two-books')

  rejectSaves(true)
  await showTools()
  await js(`document.querySelector('[aria-label="放大"]').click()`)
  await wait(`document.querySelector('.reader-save-error')?.textContent.includes('偏好暂未保存')`, 'injected preference failure')
  await js(`document.querySelector('[aria-label="关闭提示"]').click()`)
  assert.equal(await js(`Boolean(document.querySelector('.reader-save-error'))`), false, 'a dismissible save warning must close without discarding dirty preferences')
  await js(`document.querySelector('${tab('online:101')}').click()`)
  await wait(`Boolean(document.querySelector('[data-reader-transition-error]'))`, 'transition failure feedback')
  assert.equal(await js(`document.querySelector('[data-reader-tab][aria-selected="true"]').dataset.readerTab`), 'online:102')
  rejectSaves(false)
  await js(`document.querySelector('[data-reader-transition-error] button').click()`)
  await wait(`document.querySelector('${tab('online:101')}')?.getAttribute('aria-selected')==='true' && !document.querySelector('[data-reader-transition-error]')`, 'explicit save retry')
  mark('failed saving retains the active tab; explicit retry completes the intended switch')

  await js(`window.__qaReader=document.querySelector('.reader-root');document.querySelector('[aria-label="铺满阅读窗口"]').click()`)
  await wait(`document.querySelector('[data-browse-pane]').getBoundingClientRect().width===0`, 'expanded workspace')
  assert.ok(await js(`document.querySelector('[data-reader-workspace]').getBoundingClientRect().width>=innerWidth-2`))
  assert.ok(await js(`window.__qaReader===document.querySelector('.reader-root')`))
  await screenshot('workspace-expanded')
  await js(`document.querySelector('[data-reader-tab][aria-selected="true"]').focus()`)
  await press('Escape')
  assert.ok(await js(`document.querySelector('[data-browse-pane]').getBoundingClientRect().width>=300`), 'Escape restores three panes while the tab bar owns focus')
  await js(`document.querySelector('[aria-label="铺满阅读窗口"]').click()`)
  await js(`document.querySelector('[aria-label="全屏阅读"]').click()`)
  await wait('Boolean(document.fullscreenElement)', 'system fullscreen')
  await select('online:102')
  await wait(`document.querySelector('[data-reader-progress]')?.dataset.currentPage==='11'`, 'fullscreen tab switch')
  assert.ok(await js(`Boolean(document.querySelector('[aria-label="退出全屏"]'))`), 'new tab reflects the existing fullscreen state')
  await select('online:101')
  await wait(`document.querySelector('[data-reader-progress]')?.dataset.currentPage==='8'`, 'fullscreen return anchor')
  await js(`window.__qaReader=document.querySelector('.reader-root')`)
  await press('Escape')
  await wait('!document.fullscreenElement', 'exit system fullscreen')
  assert.ok(await js(`Boolean(document.querySelector('[aria-label="还原三栏布局"]'))`))
  await js(`document.querySelector('[aria-label="还原三栏布局"]').click()`)
  await wait(`document.querySelector('[data-browse-pane]').getBoundingClientRect().width>=300`, 'restore three panes')
  assert.equal(await page(), '8')
  assert.ok(await js(`window.__qaReader===document.querySelector('.reader-root')`))
  await clickText('全屏阅读')
  await wait('Boolean(document.fullscreenElement)', 'fullscreen before hiding')
  await clickText('收起阅读侧栏')
  await wait(`!document.fullscreenElement && document.querySelector('[data-reader-workspace]').getBoundingClientRect().width===0`, 'hiding exits fullscreen and restores browsing')
  await clickText('显示阅读侧栏')
  await wait(`document.querySelector('[data-reader-workspace]').getBoundingClientRect().width>=480 && document.querySelector('[data-reader-progress]')?.dataset.currentPage==='8'`, 'restore after fullscreen hide')
  assert.ok(await js(`window.__qaReader===document.querySelector('.reader-root')`))
  win.setSize(960, 640)
  await screenshot('workspace-compact')
  bounds = await geometry()
  assert.ok(bounds.browse.width >= 299 && bounds.reader.width >= 479, JSON.stringify(bounds))
  await js(`document.querySelector('nav [aria-label="展开导航"]').click()`)
  assert.ok((await geometry()).reader.width >= 479, 'expanded navigation overlays the narrow browse pane without squeezing reading')
  await js(`document.querySelector('nav [aria-label="收起导航"]').click()`)
  const outside = await js(`(()=>{const root=document.querySelector('[data-reader-workspace]').getBoundingClientRect();return [...document.querySelectorAll('.reader-toolbar button,.reader-toolbar select,.reader-workspace-header button,.reader-workspace-header summary')].filter(e=>e.getBoundingClientRect().width>0).filter(e=>{const r=e.getBoundingClientRect();return r.left<root.left-1||r.right>root.right+1}).map(e=>e.getAttribute('aria-label')||e.textContent)})()`)
  assert.deepEqual(outside, [], 'compact reader controls stay within their pane')
  await js(`document.querySelector('[aria-label="阅读设置"]').click()`)
  await screenshot('workspace-settings')
  await js(`document.querySelector('[aria-label="阅读设置"]').focus()`)
  await press('Escape')
  assert.equal(await js(`Boolean(document.querySelector('.reader-more-settings[open]'))`), false, 'Escape closes settings before changing workspace layout')
  mark('expand, fullscreen, restore and compact responsive controls preserve the active session')

  await js(`document.querySelector('${tab('online:102')}').click();document.querySelector('${tab('online:101')}').click();document.querySelector('${tab('online:102')}').click()`)
  await wait(`document.querySelector('${tab('online:102')}')?.getAttribute('aria-selected')==='true' && !document.querySelector('[data-reader-pending]')`, 'serialized rapid switches')
  await wait(`document.querySelector('[data-reader-progress]')?.dataset.currentPage==='11'`, 'rapid switch anchor')
  await js(`document.querySelector('${tab('online:102')}').focus()`)
  await press('Delete')
  await wait(`document.querySelectorAll('[data-reader-tab]').length===1 && document.querySelector('[data-reader-progress]')?.dataset.currentPage==='8'`, 'delete active tab')
  assert.ok(await js(`document.activeElement===document.querySelector('[data-reader-tab][aria-selected="true"]')`), 'closing an active tab must focus its surviving neighbor')
  await clickText('开始阅读')
  await wait(`document.querySelectorAll('[data-reader-tab]').length===2 && document.querySelector('[data-reader-progress]')?.dataset.currentPage==='11'`, 'reopen closed book')
  await js(`window.__qaReader=document.querySelector('.reader-root')`)
  await clickSelector('[data-close-reader="online:101"]')
  await wait(`document.querySelectorAll('[data-reader-tab]').length===1`, 'background close')
  assert.ok(await js(`window.__qaReader===document.querySelector('.reader-root')`))
  await clickSelector('[data-reader-tools-toggle]')
  await wait(`!document.querySelector('.reader-toolbar')`, 'tools folded before wheel interaction')
  const pointer = await js(`(()=>{const r=document.querySelector('[data-reader-viewport]').getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()`)
  wc.sendInputEvent({type:'mouseMove',...pointer})
  wc.sendInputEvent({type:'mouseWheel',...pointer,deltaY:60,deltaX:0})
  await press('H')
  await screenshot('workspace-quiet-interaction')
  assert.equal(await toolsVisible(), false, 'hover, scroll and shortcuts outside the reading viewport do not open tools')
  await clickSelector('[data-close-reader="online:102"]')
  await wait(`!document.querySelector('[data-reader-workspace]')`, 'close final tab')
  assert.ok(await js(`document.querySelector('nav').getBoundingClientRect().width>=208`))
  assert.ok(await js(`document.activeElement?.closest('[data-browse-pane],nav')`), 'final close returns keyboard focus to browsing')
  assert.equal(await js(`document.querySelectorAll('.reader-root').length`), 0)
  mark('rapid tab requests serialize; background close preserves active session; final close restores navigation')
}
