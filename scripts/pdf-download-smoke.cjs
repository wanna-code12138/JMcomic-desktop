const assert = require('node:assert/strict')
const { readFileSync, copyFileSync, readdirSync } = require('node:fs')
const { join, dirname } = require('node:path')
module.exports = async ({ win, js, wait, clickText, clickSelector, showTools, screenshot, mark, evidence }) => {
  await clickSelector('.manga-detail-actions button:nth-of-type(2)')
  await clickText('下载 (2)')
  await wait(`Boolean(document.querySelector('[data-download-format-dialog][open]'))`, 'format choice after chapter selection')
  assert.equal((await js(`window.electronAPI.downloadList()`)).length, 0, 'no network task before format confirmation')
  await clickSelector('[data-format-option="pdf"]')
  await clickSelector('[aria-label="记住下载格式"]')
  await screenshot('download-format-pdf')
  await clickText('开始下载')
  await wait(`window.electronAPI.downloadList().then(tasks=>tasks.some(task=>task.kind==='pdf'&&task.status==='completed'))`, 'merged PDF completed')
  const tasks = await js(`window.electronAPI.downloadList()`), pdf = tasks.find(task => task.kind === 'pdf')
  assert.equal(pdf.chapters.length, 2); assert.equal(pdf.totalPages, 6)
  assert.equal((await js(`window.electronAPI.settingsGet()`)).downloadFormat, 'pdf')
  const output = join(pdf.savePath, pdf.outputFile)
  assert.equal(dirname(output), pdf.savePath)
  assert.ok(readFileSync(output).subarray(0, 5).equals(Buffer.from('%PDF-')))
  assert.ok(!readdirSync(pdf.savePath).some(name => name.endsWith('.part')))
  copyFileSync(output, join(evidence, 'two-chapter-sample.pdf'))
  await clickSelector('.manga-detail-actions button:nth-of-type(2)'); await clickText('下载 (2)')
  await wait(`window.electronAPI.downloadList().then(tasks=>tasks.filter(t=>t.kind==='pdf').length===2)`, 'default bypasses format question')
  assert.equal(await js(`Boolean(document.querySelector('[data-download-format-dialog][open]'))`), false)
  await wait(`window.electronAPI.downloadList().then(tasks=>tasks.filter(t=>t.kind==='pdf'&&t.status==='completed').length===2)`, 'same-name second output')
  const second = (await js(`window.electronAPI.downloadList()`)).filter(task=>task.kind==='pdf')
  assert.notEqual(second[0].outputFile, second[1].outputFile)
  await screenshot('pdf-before-reader-tools')
  await showTools(); await clickText('阅读设置'); await clickText('选择下载格式…')
  await clickSelector('[data-format-option="images"]'); await clickText('开始下载')
  await wait(`window.electronAPI.downloadList().then(tasks=>tasks.some(t=>t.kind!=='pdf'&&t.status==='completed'))`, 'reader can override default with images')
  await clickSelector('nav [aria-label="下载"]')
  await clickText('任务')
  await wait(`Boolean(document.querySelector('[data-download-kind="pdf"]'))`, 'PDF visible in unified task list')
  await screenshot('download-unified-tasks')
  mark('format confirmation/default/override, two chapters in one root-level PDF, unique output, images retain chapter folders', { output, pages: pdf.totalPages })
}
