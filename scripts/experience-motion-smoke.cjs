const assert = require('node:assert/strict')
module.exports = async ({win,js,wait,clickSelector,screenshot,mark}) => {
  const wc=win.webContents
  wc.send('download:progress',{taskId:991,kind:'pdf',status:'downloading',mangaTitle:'动效检查样章',chapterTitle:'PDF',totalPages:10,downloadedPages:5})
  await wait(`Boolean([...document.querySelectorAll('[role="button"]')].find(e=>e.textContent==='下载中 1'))`,'download indicator')
  const chip=await js(`(()=>{const r=[...document.querySelectorAll('[role="button"]')].find(e=>e.textContent==='下载中 1').getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()`)
  wc.sendInputEvent({type:'mouseMove',...chip})
  await wait(`document.body.textContent.includes('动效检查样章 - PDF')`,'download popover visible')
  assert.ok(await js(`Boolean([...document.querySelectorAll('div')].find(e=>e.style.transform==='scaleX(0.5)'))`),'download progress animates a transform without relayout')
  wc.sendInputEvent({type:'mouseMove',x:10,y:10})
  await wait(`Boolean([...document.querySelectorAll('[data-exiting="true"]')].find(e=>e.textContent.includes('动效检查样章')))`,'download popover exit motion')
  await wait(`!document.body.textContent.includes('动效检查样章 - PDF')`,'download popover released')
  wc.send('download:progress',{taskId:991,kind:'pdf',status:'completed'})
  await clickSelector('nav [aria-label="设置"]')
  await wait(`Boolean(document.querySelector('[data-page-id="settings"] input'))`,'settings ready')
  await js(`document.querySelector('nav [aria-label="收藏"]').click()`)
  await wait(`document.querySelector('[data-page-id="settings"]')?.getAnimations().some(a=>a.playState==='running')`,'outgoing page exit motion')
  assert.equal(await js(`document.querySelector('[data-page-id="settings"]').inert`),true)
  await screenshot('motion-page-transition')
  await clickSelector('[data-reader-tools-toggle]')
  await wait(`Boolean(document.querySelector('.reader-toolbar'))`,'tools mounted')
  await screenshot('motion-tools-in')
  await js(`document.querySelector('[data-reader-tools-toggle]').click()`)
  await wait(`Boolean(document.querySelector('.reader-toolbar[data-exiting="true"]'))`,'tools exit motion')
  await wait(`!document.querySelector('.reader-toolbar')`,'tools released')
  await js(`document.querySelector('[data-reader-tab]').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,clientX:860,clientY:80}))`)
  await wait(`Boolean(document.querySelector('.workspace-menu'))`,'tab menu visible')
  await js(`document.querySelector('.workspace-menu').dispatchEvent(new KeyboardEvent('keydown',{bubbles:true,key:'Escape'}))`)
  await wait(`Boolean(document.querySelector('.workspace-menu[data-exiting="true"]'))`,'tab menu exit motion')
  assert.equal(await js(`document.querySelector('.workspace-menu').inert`),true)
  await wait(`!document.querySelector('.workspace-menu')`,'tab menu released')
  await clickSelector('[aria-label="收起阅读侧栏"]')
  await screenshot('motion-reader-hidden')
  await clickSelector('[data-reader-visibility-toggle]')
  await js(`window.__motionReader=document.querySelector('.reader-root')`)
  await js(`(async()=>{for(let i=0;i<8;i++){document.querySelector('nav [aria-label="'+(i%2?'收藏':'设置')+'"]').click();await new Promise(resolve=>setTimeout(resolve,30))}})()`)
  await wait(`document.getAnimations().every(a=>a.playState!=='running'||a.effect.getTiming().iterations===Infinity)`,'rapid navigation settles')
  if (process.env.JM_QA_VISIBLE === '1') {
    assert.equal(win.isVisible(),true,'the native window must be visible before occlusion')
    win.hide()
    assert.equal(win.isVisible(),false,'the native window must actually hide')
    await js(`document.querySelector('nav [aria-label="设置"]').click()`)
    await new Promise(resolve=>setTimeout(resolve,400))
    win.showInactive();wc.invalidate()
    assert.equal(win.isVisible(),true,'the native window must actually resume')
    await wait(`document.getAnimations().every(a=>a.playState!=='running'||a.effect.getTiming().iterations===Infinity)`,'occluded window resumes without stale motion')
    mark('native window visibility changes true/false/true and interrupted motion settles after restore')
  }
  assert.equal(await js(`window.__motionReader===document.querySelector('.reader-root')`),true,'interruptions and occlusion preserve the active reader')
  assert.equal(await js(`getComputedStyle(document.querySelector('.reading-pane')).transform`),'none')
  await screenshot('motion-resumed')
  await clickSelector('nav [aria-label="设置"]')
  await clickSelector('[aria-label="界面动画"]')
  // ExperienceSettings applies the preference after the real settingsSet persistence promise resolves.
  await wait(`document.documentElement.dataset.motion==='off'`,'saved animation preference applied')
  assert.equal(await js(`document.documentElement.dataset.motion`),'off')
  await js(`document.querySelector('nav [aria-label="收藏"]').click()`)
  await wait(`document.querySelector('nav [aria-label="收藏"]').getAttribute('aria-current')==='page'`,'navigation without motion')
  assert.equal(await js(`document.getAnimations().filter(a=>a.playState==='running').length`),0)
  await clickSelector('nav [aria-label="设置"]');await clickSelector('[aria-label="界面动画"]')
  await wait(`document.documentElement.dataset.motion==='on'`,'animations restored before system override')
  wc.debugger.attach('1.3')
  await wc.debugger.sendCommand('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]})
  await wait(`document.documentElement.dataset.motion==='off'`,'system reduced motion wins')
  wc.debugger.detach()
  mark('pages, tools, context menu and download popover enter/exit; progress uses transform; animation-off and system reduced-motion stop all motion')
}
