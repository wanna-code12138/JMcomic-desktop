const assert = require('node:assert/strict')
module.exports = async ({ win, js, wait, clickSelector, clickText, screenshot, mark }) => {
  await clickSelector('nav [aria-label="设置"]')
  await wait(`document.querySelector('[data-browse-pane]').textContent.includes('外观')`, 'settings loaded')
  assert.ok(await js(`Boolean(document.querySelector('[aria-label="界面动画"]'))`), 'animation has an independent switch')
  await clickSelector('[aria-label="界面动画"]')
  await wait(`document.documentElement.dataset.motion==='off'`, 'animations immediately disabled')
  assert.equal((await js(`window.electronAPI.settingsGet()`)).animationsEnabled, false)
  const gpu = await js(`window.electronAPI.graphicsGet()`)
  await clickSelector('[aria-label="GPU 硬件加速"]')
  await wait(`document.querySelector('[data-browse-pane]').textContent.includes('重启后生效')`, 'restart explicitly required')
  const changed = await js(`window.electronAPI.graphicsGet()`)
  assert.equal(changed.requested, !gpu.requested)
  assert.equal(changed.runningPreference, gpu.runningPreference)
  assert.equal((await js(`window.electronAPI.settingsGet()`)).animationsEnabled, false)
  await clickSelector('[aria-label="下次启动恢复阅读标签"]')
  await clickSelector('[data-new-reader-tab]')
  await wait(`Boolean(document.querySelector('[data-reader-start]'))`, 'new tab')
  await wait(`window.electronAPI.workspaceGet().then(s=>s?.tabs.length===2)`, 'workspace metadata persisted')
  const saved = await js(`window.electronAPI.workspaceGet()`)
  assert.equal(saved.tabs[1].kind, 'start')
  assert.ok(!JSON.stringify(saved).includes('imageData'))
  await js(`document.querySelector('[data-reader-tab="online:101"]').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,clientX:850,clientY:70}))`)
  await clickText('重命名标签')
  await js(`document.querySelector('[aria-label="标签名称"]').select()`)
  await win.webContents.insertText('跨进程恢复书签')
  await clickText('保存名称')
  await js(`document.querySelector('[data-reader-tab="online:101"]').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,clientX:850,clientY:70}))`)
  await clickText('固定标签')
  await wait(`window.electronAPI.workspaceGet().then(s=>s?.tabs[0].pinned && s.tabs[0].customTitle==='跨进程恢复书签')`, 'custom title and pin persisted')
  const divider = '[role="separator"][aria-label="调整浏览与阅读宽度"]'
  assert.ok(await js(`Boolean(document.querySelector('${divider}'))`), 'split panes expose an accessible divider')
  const before = await js(`document.querySelector('[data-browse-pane]').getBoundingClientRect().width`)
  await js(`document.querySelector('${divider}').focus()`)
  win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Right' })
  win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Right' })
  await wait(`document.querySelector('[data-browse-pane]').getBoundingClientRect().width>${before+5}`, 'keyboard divider resize')
  assert.ok(await js(`document.querySelector('[data-reader-workspace]').getBoundingClientRect().width>=480`))
  await screenshot('settings-and-start')
  await clickSelector('[aria-label="界面动画"]')
  await wait(`document.documentElement.dataset.motion==='on'`, 'animation restored')
  mark('independent animation/GPU controls, restart state, persistent workspace, accessible divider')
}
